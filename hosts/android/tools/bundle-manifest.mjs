// Generates BundleManifest.java for the Android virtual-HTTPS origin from the
// allowlisted engine asset bundle: the exact servable file set and the CSP
// hashes of inline page scripts. Refuses files the host policy cannot serve.
// usage: node bundle-manifest.mjs <asset-dir> <output.java> [entry]
import { createHash } from "node:crypto";
import { mkdirSync, lstatSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";

export const MIME = { ".wasm": "application/wasm", ".js": "text/javascript", ".mjs": "text/javascript", ".html": "text/html", ".css": "text/css", ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png" };
const ALLOWED = new Set(JSON.parse(readFileSync(new URL("../../../engine/assets.json", import.meta.url), "utf8")).files.map(file => file.path));
const SAFE = /^[A-Za-z0-9._\/-]+$/;

function walk(root, dir = root, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    const info = lstatSync(path);
    if (info.isSymbolicLink()) throw new Error(`symlink in bundle: ${path}`);
    if (info.isDirectory()) walk(root, path, out);
    else if (info.isFile()) out.push(relative(root, path).split(sep).join("/"));
    else throw new Error(`unsupported bundle entry ${path}`);
  }
  return out;
}

export function bundleManifest(root, entry = "engine/page.html") {
  const files = walk(root).filter(path => path !== "asset-manifest.json");
  for (const file of files) if (!ALLOWED.has(file)) throw new Error(`bundle file ${file} is outside engine/assets.json`);
  if (!files.includes(entry)) throw new Error(`bundle entry ${entry} missing`);
  const hashes = new Set();
  for (const file of files) {
    const extension = file.slice(file.lastIndexOf("."));
    if (file.lastIndexOf(".") <= file.lastIndexOf("/") || !(extension.toLowerCase() in MIME)) throw new Error(`bundle file ${file} has no allowlisted MIME type`);
    if (!SAFE.test(file) || file.split("/").some((part) => part === "" || part === "." || part === "..") || file.length > 511) throw new Error(`bundle path ${file} is not servable`);
    if (extension.toLowerCase() !== ".html") continue;
    const html = readFileSync(join(root, file), "utf8");
    if (/<[a-z][^>]*\son[a-z]+\s*=/i.test(html)) throw new Error(`${file}: inline event handlers are blocked by the bundle CSP`);
    if (/javascript:/i.test(html)) throw new Error(`${file}: javascript: URLs are blocked by the bundle CSP`);
    for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
      if (/\bsrc\s*=/i.test(match[1])) continue;
      hashes.add(`'sha256-${createHash("sha256").update(match[2], "utf8").digest("base64")}'`);
    }
  }
  return { files, hashes: [...hashes].sort() };
}

export function javaSource({ files, hashes }) {
  return `// generated by hosts/android/tools/bundle-manifest.mjs — do not edit
package dev.nativetron.app;

import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;

final class BundleManifest {
  private BundleManifest() {}
  static final Set<String> FILES = Collections.unmodifiableSet(new HashSet<>(Arrays.asList(
${files.map((file) => `    "${file}"`).join(",\n")}
  )));
  static final String SCRIPT_HASHES = "${hashes.join(" ")}";
}
`;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [root, output, entry] = process.argv.slice(2);
  if (!root || !output) { console.error("usage: bundle-manifest.mjs <asset-dir> <output.java> [entry]"); process.exit(2); }
  const manifest = bundleManifest(root, entry);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, javaSource(manifest));
  console.log(`bundle manifest: ${manifest.files.length} files, ${manifest.hashes.length} inline script hash(es)`);
}
